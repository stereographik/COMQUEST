"""Turn Django's Eden models (CQ_CompoLab_django.VR/mission.sqm, one layer per model) into
ComQuest.Altis/cfg/compositions.sqf.

    python3 django_to_sqf.py <mission.sqm> <compositions.sqf>

Each layer becomes CQ_compos entry  name -> [[class, [right, forward, height], dir, role], ...]
measured from the layer's KEY object (offsets turned into the key's own frame, dir relative to it).
role: "key" (the objective itself, placed by CQ_fnc_hqBuild), "aa" (an AA gun spot), "term"
(hack terminal spot), "pad" (helipad), "" (decor).
The sqm must be saved unbinarized (Eden: Save without "Binarize the scenario file").
"""
import math, re, sys

LAYERS = {   # layer -> (composition name, key class)
    "AAPIT":      ("aaPit",  "I_G_Mortar_01_F"),
    "HMGTOWER":   ("hmgTower", "Land_Cargo_Patrol_V3_F"),
    "RADIOTOWER": ("radio",  "Land_TTowerBig_2_F"),
    "DEPOT":      ("depot",  "Land_Cargo_House_V3_F"),
    "FUEL":       ("fuel",   "Land_Airport_01_hangar_F"),
    "HQMODEL":    ("hq",     "Land_Cargo_HQ_V3_F"),
    "OUTPOST":    ("outpost", "Land_Cargo_Patrol_V3_F"),
}
ROLE = {"I_G_Mortar_01_F": "aa", "Land_MultiScreenComputer_01_olive_F": "term", "Land_HelipadSquare_F": "pad"}

def parse(path):
    t = open(path, encoding="latin1").read().replace("\r", "")
    tok = re.compile(r'class\s+(\w+)\s*\{|\};|(\w+)(\[\])?\s*=\s*(\{[^;]*\}|"[^"]*"|[^;]*);')
    root = {"_c": []}; st = [root]
    for m in tok.finditer(t):
        if m.group(1):
            n = {"_n": m.group(1), "_c": []}; st[-1]["_c"].append(n); st.append(n)
        elif m.group(0) == "};":
            st.pop()
        else:
            st[-1][m.group(2)] = m.group(4)
    out = {}
    def walk(n, layer):
        for c in n["_c"]:
            dt = c.get("dataType", "").strip('"')
            if dt == "Layer":
                walk(c, c.get("name", "").strip('"'))
            elif dt == "Object":
                pi = next(k for k in c["_c"] if k["_n"] == "PositionInfo")
                p = [float(x) for x in pi["position"].strip("{}").split(",")]
                a = [float(x) for x in pi.get("angles", "{0,0,0}").strip("{}").split(",")]
                out.setdefault(layer, []).append({
                    "cls": c.get("type", "").strip('"'), "x": p[0], "y": p[2],
                    "z": float(c["atlOffset"]) if "atlOffset" in c else 0.0,
                    "dir": math.degrees(a[1]) % 360})
            else:
                walk(c, layer)
    walk(root, "")
    return out

def main(src, dst):
    layers = parse(src)
    lines = ["// generated by tools/compolab/django_to_sqf.py from Django's Eden models (CQ_CompoLab_django.VR)",
             "// name -> [[class, [right, forward, height], dir, role], ...] from the model's key object",
             "// role: key = the objective itself, aa = an AA gun spot, term = hack terminal, pad = helipad, \"\" = decor",
             "CQ_compos = createHashMapFromArray ["]
    ents = []
    for layer, (name, key) in LAYERS.items():
        objs = layers.get(layer, [])
        k = next((o for o in objs if o["cls"] == key), None)
        if k is None:
            print(f"!! {layer}: key {key} missing, skipped"); continue
        h = math.radians(k["dir"])
        rows = []
        for o in objs:
            ex, ny = o["x"] - k["x"], o["y"] - k["y"]
            right = ex * math.cos(h) - ny * math.sin(h)
            fwd = ex * math.sin(h) + ny * math.cos(h)
            role = "key" if o is k else ROLE.get(o["cls"], "")
            cls = "O_static_AA_F" if o["cls"] == "I_G_Mortar_01_F" else o["cls"]
            if role == "key" and layer == "AAPIT": cls = "O_static_AA_F"
            z = 0.0 if abs(o["z"]) < 0.01 else o["z"]
            rows.append(f'["{cls}",[{right:.2f},{fwd:.2f},{z:.2f}],{(o["dir"] - k["dir"]) % 360:.1f},"{role}"]')
        # key first
        rows.sort(key=lambda r: 0 if r.endswith('"key"]') else 1)
        rad = max(math.hypot(o["x"] - k["x"], o["y"] - k["y"]) for o in objs)
        print(f"{name}: {len(rows)} objects, {rad:.0f} m from the key")
        ents.append(f'    ["{name}", [\n        ' + ",\n        ".join(rows) + "\n    ]]")
    lines.append(",\n".join(ents))
    lines.append("];")
    open(dst, "w").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
